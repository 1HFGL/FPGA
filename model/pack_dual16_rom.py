"""Build a lossless, physical two-read-port coefficient ROM for both 16-voice groups.

Only redundant bits are factored out: inc[31], amp[15:13], padding are zero;
phase/noise depend on preset/component, not note. Assert every condition and
reconstruct ALL 12288 coefficients before emitting 45 GW5A DPB primitives.
The original piano_v3_modes.mem remains the source of truth. --check is read-only.
"""
from pathlib import Path
import argparse
import hashlib

ROOT = Path(__file__).resolve().parents[1]


def generate():
    source = ROOT / 'rtl/rom/piano_v3_modes.mem'
    words = [int(x, 16) for x in source.read_text().splitlines()]
    assert len(words) == 16384
    metadata = [(words[p * 8192 + i] & 1023) | ((words[p * 8192 + i] >> 74) << 10)
                for p in range(2) for i in range(48)]
    packed = []
    for record in range(256):
        for component in range(48):
            word = words[record * 64 + component]
            inc, amp, decay = (word >> 42) & 0xffffffff, (word >> 26) & 65535, (word >> 10) & 65535
            assert inc < 2**31 and amp < 2**13 and word < 2**75, 'Coefficient width changed'
            meta = metadata[(record // 128) * 48 + component]
            rebuilt = ((meta >> 10) << 74) | (inc << 42) | (amp << 26) | (decay << 10) | (meta & 1023)
            assert rebuilt == word, 'Note-dependent phase/noise requires a new packing format'
            packed.append((inc << 29) | (amp << 16) | decay)
    lines = ['// Generated by model/pack_dual16_rom.py; do not edit coefficients here.',
             '// Source SHA256: ' + hashlib.sha256(source.read_bytes()).hexdigest(),
             '// 3 x 4096 x 60 bits, physically shared by two independent read ports.',
             'module modal_coeff_rom_dual(',
             ' input wire clk, en_a, en_b,',
             ' input wire [13:0] address_a, address_b,',
             ' input wire [6:0] metadata_a, metadata_b,',
             ' output wire [75:0] data_a, data_b);',
             ' reg [1:0] bank_a, bank_b;',
             ' reg [10:0] meta_a, meta_b;',
             ' wire [59:0] row_a[0:2], row_b[0:2];',
             ' wire [59:0] word_a=row_a[bank_a], word_b=row_b[bank_b];',
             " assign data_a={1'b0,meta_a[10],1'b0,word_a[59:29],3'd0,word_a[28:16],word_a[15:0],meta_a[9:0]};",
             " assign data_b={1'b0,meta_b[10],1'b0,word_b[59:29],3'd0,word_b[28:16],word_b[15:0],meta_b[9:0]};",
             ' function [10:0] metadata;', ' input [6:0] index;', ' begin case(index)']
    lines += [f" 7'd{i}: metadata=11'h{m:03x};" for i, m in enumerate(metadata)]
    lines += [" default: metadata=11'd0;", ' endcase end endfunction',
              ' always @(posedge clk) begin',
              '  if(en_a)begin bank_a<=address_a[13:12];meta_a<=metadata(metadata_a);end',
              '  if(en_b)begin bank_b<=address_b[13:12];meta_b<=metadata(metadata_b);end',
              ' end']
    for bank in range(3):
        for nibble in range(15):
            name = f'rom_{bank}_{nibble}'
            lines += [f' wire [15:0] {name}_a, {name}_b;',
                      f' assign row_a[{bank}][{nibble * 4}+:4]={name}_a[3:0];',
                      f' assign row_b[{bank}][{nibble * 4}+:4]={name}_b[3:0];',
                      f' DPB {name}(.DOA({name}_a),.DOB({name}_b),',
                      "  .DIA(16'd0),.DIB(16'd0),.BLKSELA(3'd0),.BLKSELB(3'd0),",
                      "  .ADA({address_a[11:0],2'b00}),.ADB({address_b[11:0],2'b00}),",
                      "  .WREA(1'b0),.WREB(1'b0),.CLKA(clk),.CLKB(clk),",
                      f"  .CEA(en_a && address_a[13:12]==2'd{bank}),.CEB(en_b && address_b[13:12]==2'd{bank}),",
                      "  .OCEA(1'b1),.OCEB(1'b1),.RESETA(1'b0),.RESETB(1'b0));",
                      f' defparam {name}.BIT_WIDTH_0=4, {name}.BIT_WIDTH_1=4;',
                      f" defparam {name}.READ_MODE0=1'b0, {name}.READ_MODE1=1'b0;"]
            for block in range(64):
                value = sum(((packed[bank * 4096 + block * 64 + i] >> (4 * nibble)) & 15) << (4 * i)
                            for i in range(64))
                lines += [f" defparam {name}.INIT_RAM_{block:02X}=256'h{value:064x};"]
    lines += ['endmodule', '']
    return '\n'.join(lines)


if __name__ == '__main__':
    p = argparse.ArgumentParser()
    p.add_argument('--check', action='store_true')
    args = p.parse_args()
    target = ROOT / 'rtl/rom/modal_coeff_rom_dual.v'
    body = generate()
    if args.check:
        # The source-byte SHA in the header is a generation-time breadcrumb.
        # Git may change only .mem line endings on another host; compare every
        # executable declaration/initialization, not that informational comment.
        assert target.read_text(encoding='ascii').splitlines()[2:] == body.splitlines()[2:], 'Stale dual-port ROM; regenerate'
    else:
        target.write_text(body, encoding='ascii', newline='\n')
    print('PASS dual16 ROM: all 12288 coefficients exactly reconstructed; 45 physical dual-port BSRAMs')
