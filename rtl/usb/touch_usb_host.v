// Device-specific full-speed HID host for the measured 1A86:E5E3 touchscreen.
// No software CPU; EP0 is a bounded control-transfer engine and reports use a
// separate interrupt endpoint. Packet bytes are never published before CRC.
module touch_usb_host #(
    parameter integer CLOCKS_PER_MS=48000,
    parameter integer ATTACH_MS=100,RESET_MS=20,RECOVERY_MS=10
)(
    input wire clk,rst_n,
    input wire [1:0] line_state,
    input wire host_transmitting,
    output wire bus_reset,link_enable,
    output reg connected,
    output reg report_valid,
    input wire report_ready,
    output reg [415:0] report_data,
    output reg [7:0] debug_state,
    output wire command_valid,input wire command_ready,
    output wire [7:0] command_pid,
    output wire [6:0] command_address,
    output wire [3:0] command_endpoint,
    output wire command_toggle,
    output wire [6:0] command_length,
    output wire [63:0] command_payload,
    input wire link_frame_tick,transaction_done,transaction_error,
    input wire [7:0] response,
    input wire [15:0] received_length,
    input wire [511:0] received_payload
);
    localparam DETACHED=0,RESET=1,RECOVER=2,LAUNCH=3,WAIT_CONTROL=4,
        ADDRESS_GAP=5,PARSE=6,POLL=7,POLL_WAIT=8,RESTART=9,REPORT=10;
    reg [3:0] state,step;
    reg [15:0] ms_clock;
    reg ms_tick;
    reg [7:0] delay_ms,stable_ms,poll_ms,interval_ms;
    reg [17:0] se0_clocks;
    reg [3:0] failures,endpoint;
    reg toggle,poll_due;
    reg [6:0] address,mps;
    reg [7:0] configuration;
    reg [9:0] configuration_length,parse_offset;
    reg [15:0] hid_length;
    reg selected_interface,found_interface,found_endpoint,found_hid;
    reg control_start;
    reg [63:0] setup;
    wire control_ready,control_done,control_success,control_stalled;
    wire [9:0] control_length;
    wire [1023:0] control_data;
    wire cv,cr,ct;
    wire [7:0] cp;
    wire [6:0] ca,cl;
    wire [3:0] ce;
    wire [63:0] cb;
    wire polling=state==POLL || state==POLL_WAIT || state==REPORT;
    assign bus_reset=state==RESET;
    assign link_enable=state!=DETACHED && state!=RESET && state!=RESTART;
    assign command_valid=polling ? state==POLL && poll_due && report_ready : cv;
    assign cr=command_ready && !polling;
    assign command_pid=polling?8'h69:cp;
    assign command_address=polling?7'd1:ca;
    assign command_endpoint=polling?endpoint:ce;
    assign command_toggle=polling?toggle:ct;
    assign command_length=polling?7'd0:cl;
    assign command_payload=cb;
    touch_usb_control u_control(.clk(clk),.rst_n(rst_n && link_enable),.frame_tick(link_frame_tick),
        .start(control_start),.ready(control_ready),.setup_data(setup),.device_address(address),.ep0_max_packet(mps),
        .done(control_done),.success(control_success),.stalled(control_stalled),
        .result_length(control_length),.result_data(control_data),
        .command_valid(cv),.command_ready(cr),.command_pid(cp),.command_address(ca),
        .command_endpoint(ce),.command_toggle(ct),.command_length(cl),.command_payload(cb),
        .transaction_done(transaction_done && !polling),.transaction_error(transaction_error),
        .response(response),.received_length(received_length),.received_payload(received_payload));
    function [7:0] field;
        input [1023:0] buffer;
        input [9:0] offset;
        begin field=offset<128?buffer[offset*8+:8]:8'd0;end
    endfunction
    // 枚举阶段逐字节收集9字节描述符头，共用一个128选1读口。
    // 只给每个配置描述符增加9个48MHz周期；正常触摸轮询和音频节拍不变。
    // 完整窗口就绪后才解析，断线/复位或新控制传输会重新开始收集。
    reg [71:0] descriptor_fields;
    reg [3:0] descriptor_index;
    reg descriptor_ready;
    wire [9:0] descriptor_address=parse_offset+{6'd0,descriptor_index};
    wire [7:0] descriptor_byte=field(control_data,descriptor_address);
    wire [7:0] descriptor_length=descriptor_fields[7:0],descriptor_type=descriptor_fields[15:8];
    wire detached_long=se0_clocks>=CLOCKS_PER_MS*3;
    always @(posedge clk or negedge rst_n)begin
        if(!rst_n)begin
            ms_clock<=0;ms_tick<=0;se0_clocks<=0;
        end else begin
            ms_tick<=ms_clock==CLOCKS_PER_MS-1;
            if(ms_clock==CLOCKS_PER_MS-1)ms_clock<=0;else ms_clock<=ms_clock+1'b1;
            // SOF/OUT traffic is generated by us even with no device attached.
            // Do not let our own J/K/EOP reset the idle-SE0 detach observation.
            if(host_transmitting)begin end
            else if(line_state==0 && state!=RESET)begin
                if(se0_clocks<CLOCKS_PER_MS*3)se0_clocks<=se0_clocks+1'b1;
            end else se0_clocks<=0;
        end
    end
    always @(posedge clk or negedge rst_n)begin
        if(!rst_n)begin
            state<=DETACHED;step<=0;delay_ms<=0;stable_ms<=0;poll_ms<=0;interval_ms<=1;
            failures<=0;endpoint<=0;toggle<=0;poll_due<=0;address<=0;mps<=8;configuration<=0;
            configuration_length<=0;parse_offset<=0;hid_length<=0;
            descriptor_fields<=0;descriptor_index<=0;descriptor_ready<=0;
            selected_interface<=0;found_interface<=0;found_endpoint<=0;found_hid<=0;
            control_start<=0;setup<=0;connected<=0;report_valid<=0;report_data<=0;debug_state<=0;
        end else begin
            control_start<=0;debug_state<={state,step};
            if(report_valid && report_ready)report_valid<=0;
            if(link_frame_tick && polling)begin
                if(poll_ms>=interval_ms-1)begin poll_due<=1;poll_ms<=0;end
                else poll_ms<=poll_ms+1'b1;
            end
            if(detached_long && state!=DETACHED && state!=RESET && state!=RECOVER)begin
                state<=RESTART;connected<=0;report_valid<=0;
            end else case(state)
                DETACHED:begin
                    connected<=0;address<=0;mps<=8;step<=0;failures<=0;
                    if(line_state==2'b01)begin
                        if(ms_tick)begin
                            if(stable_ms>=ATTACH_MS-1)begin state<=RESET;delay_ms<=RESET_MS;stable_ms<=0;end
                            else stable_ms<=stable_ms+1'b1;
                        end
                    end else stable_ms<=0;
                end
                RESET:if(ms_tick)begin
                    if(delay_ms==0)begin state<=RECOVER;delay_ms<=RECOVERY_MS;end
                    else delay_ms<=delay_ms-1'b1;
                end
                RECOVER:if(ms_tick)begin
                    if(delay_ms==0)state<=LAUNCH;else delay_ms<=delay_ms-1'b1;
                end
                LAUNCH:if(control_ready)begin
                    control_start<=1;state<=WAIT_CONTROL;
                    case(step)
                        0:setup<=64'h0008_0000_0100_0680;
                        1:setup<=64'h0012_0000_0100_0680;
                        2:setup<=64'h0000_0000_0001_0500;
                        3:setup<=64'h0009_0000_0200_0680;
                        4:setup<={{6'd0,configuration_length},16'd0,16'h0200,8'h06,8'h80};
                        5:setup<={16'd0,16'd0,8'd0,configuration,8'h09,8'h00};
                        6:setup<={hid_length,16'd0,16'h2200,8'h06,8'h81};
                        7:setup<=64'h0002_0000_0302_01a1;
                        default:setup<=64'h0000_0000_0000_0a21;
                    endcase
                end
                WAIT_CONTROL:if(control_done)begin
                    if(!control_success && !(step==8 && control_stalled))state<=RESTART;
                    else begin
                        state<=LAUNCH;step<=step+1'b1;
                        case(step)
                            0:begin
                                if(control_length!=8 || field(control_data,0)!=18 || field(control_data,1)!=1 ||
                                   !(field(control_data,7)==8 || field(control_data,7)==16 || field(control_data,7)==32 || field(control_data,7)==64))state<=RESTART;
                                else mps<=control_data[56+:7];
                            end
                            1:if(control_length!=18 || control_data[64+:16]!=16'h1a86 ||
                                 control_data[80+:16]!=16'he5e3 || field(control_data,17)==0)state<=RESTART;
                            2:begin address<=1;delay_ms<=3;state<=ADDRESS_GAP;end
                            3:begin
                                if(control_length!=9 || field(control_data,0)!=9 || field(control_data,1)!=2 ||
                                   control_data[16+:16]<9 || control_data[16+:16]>128 || field(control_data,5)==0)state<=RESTART;
                                else begin configuration_length<=control_data[16+:10];configuration<=field(control_data,5);end
                            end
                            4:begin
                                if(control_length!=configuration_length)state<=RESTART;
                                else begin
                                    parse_offset<=0;selected_interface<=0;found_interface<=0;
                                    descriptor_index<=0;descriptor_ready<=0;
                                    found_endpoint<=0;found_hid<=0;state<=PARSE;
                                end
                            end
                            6:if(control_length!=hid_length)state<=RESTART;
                            7:if(control_length!=2 || control_data[15:0]!=16'h0602)state<=RESTART;
                            8:begin connected<=1;toggle<=0;poll_due<=1;poll_ms<=0;state<=POLL;end
                            default:begin end
                        endcase
                    end
                end
                ADDRESS_GAP:if(ms_tick)begin
                    if(delay_ms==0)state<=LAUNCH;else delay_ms<=delay_ms-1'b1;
                end
                PARSE:begin
                    if(parse_offset==configuration_length)begin
                        if(found_interface && found_hid && found_endpoint)begin step<=5;state<=LAUNCH;end
                        else state<=RESTART;
                    end else if(!descriptor_ready)begin
                        descriptor_fields[descriptor_index*8+:8]<=descriptor_byte;
                        if(descriptor_index==8)descriptor_ready<=1;
                        else descriptor_index<=descriptor_index+1'b1;
                    end else if(descriptor_length<2 || parse_offset+descriptor_length>configuration_length)state<=RESTART;
                    else begin
                        parse_offset<=parse_offset+descriptor_length;
                        descriptor_index<=0;descriptor_ready<=0;
                        if(descriptor_type==4)begin
                            selected_interface<=descriptor_length>=9 && descriptor_fields[16+:8]==0 &&
                                descriptor_fields[24+:8]==0 && descriptor_fields[40+:8]==3;
                            if(descriptor_length>=9 && descriptor_fields[16+:8]==0 && descriptor_fields[24+:8]==0 &&
                               descriptor_fields[40+:8]==3)found_interface<=1;
                        end
                        if(selected_interface && descriptor_type==8'h21 && descriptor_length>=9 && descriptor_fields[48+:8]==8'h22)begin
                            hid_length<=descriptor_fields[56+:16];
                            found_hid<=(descriptor_fields[56+:16]>0 && descriptor_fields[56+:16]<=512);
                        end
                        if(selected_interface && descriptor_type==5 && descriptor_length>=7 &&
                           descriptor_fields[16+:8]>=8'h81 && descriptor_fields[16+:8]<=8'h8f &&
                           descriptor_fields[24+:8]==3 && descriptor_fields[40+:8]==0 &&
                           descriptor_fields[32+:8]>=52 && descriptor_fields[32+:8]<=64 && descriptor_fields[48+:8]!=0)begin
                            endpoint<=descriptor_fields[16+:4];interval_ms<=descriptor_fields[48+:8];found_endpoint<=1;
                        end
                    end
                end
                POLL:if(command_valid && command_ready)begin state<=POLL_WAIT;poll_due<=0;end
                POLL_WAIT:if(transaction_done)begin
                    state<=POLL;
                    if(!transaction_error && response==8'h5a)failures<=0;
                    else if(!transaction_error && (response==8'hc3 || response==8'h4b))begin
                        failures<=0;
                        if(response==(toggle?8'h4b:8'hc3))begin
                            if(received_length==52 && received_payload[7:0]==1)begin
                                toggle<=!toggle;report_data<=received_payload[415:0];report_valid<=1;state<=REPORT;
                            end else state<=RESTART;
                        end
                    end else if(response==8'h1e || failures==7)state<=RESTART;
                    else failures<=failures+1'b1;
                end
                REPORT:if(report_valid && report_ready)state<=POLL;
                RESTART:begin connected<=0;report_valid<=0;stable_ms<=0;state<=DETACHED;end
                default:state<=RESTART;
            endcase
        end
    end
endmodule
